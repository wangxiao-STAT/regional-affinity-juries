"""Build the public code-and-data deposit in a separate directory.

python -I nhb/src/make_release.py <out_dir>     (an existing <out_dir> is rebuilt; its .git is kept)

Copies src/, tests/, jobs/ (with the working directory replaced by $REPO), data/README.md, the
download manifest, the processed tables and the result tables, and writes nothing back into nhb/.
Juror names are replaced by pseudonymous identifiers that are stable across files, so that ballots by
the same person can still be linked (the movers analysis needs it); the name-to-identifier mapping
is not written anywhere. Columns holding raw text lines of the source files, and the two Wikipedia
manager tables that list coaches by name, are left out; src/fetch_managers.py and
src/coach_history.py rebuild them from Wikipedia. Raw downloads (FIFA's PDFs, web pages) are not
redistributed; data/raw/fifa/manifest.csv and the fetch scripts give their sources. Covariance
matrices (*.npz, about 200 MB) are left out and regenerated by fit_pooled.py and fit_combined.py.
"""
import shutil
import sys
import unicodedata
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
PROC = ROOT / "data" / "processed"

# column -> namespace of its pseudonymous identifiers; one mapping per namespace across all files
NAME_COLUMNS = {
    "fifa_ballots.csv": {"voter": "F"},
    "fifa_ballots_raw.csv": {"voter": "F"},
    "fifa_long.csv": {"voter": "F"},
    "fifa_coach_nationality_all.csv": {"voter": "F", "coach_id": "C"},
    "fifa_coach_nationality.csv": {"voter": "F"},
    "bdo_ballots.csv": {"juror": "B"},
    "bdo_ballots_companion.csv": {"juror": "B"},
    "bdo_ballots_raw.csv": {"juror": "B"},
    "bdo_wiki_ballots.csv": {"juror": "B"},
    "bdo_long.csv": {"voter": "B"},
    "bdo_companion_issues.csv": {"voter": "B"},
}
DROP_COLUMNS = {
    "fifa_ballots.csv": ["line"],
    "fifa_ballots_raw.csv": ["line"],
    "fifa_coach_nationality_all.csv": ["matched_name"],
    "fifa_coach_nationality.csv": ["listed", "matched_name", "page"],     # page: the coach's Wikipedia page
    "bdo_parse_issues.csv": ["text"],
}
LEAVE_OUT = {"coach_history_entries.csv", "manager_snapshots.csv",   # coaches listed by name
             "esc_jurors.csv"}                                       # Eurovision jurors by name
# the Slurm jobs that produce the reported results, in order (others were superseded during the review)
RELEASE_JOBS = {"rv1_all.sbatch": "01_fits_and_analyses.sbatch", "robustness.sbatch": "02_robustness.sbatch",
                "rv1_cf2.sbatch": "03_counterfactuals.sbatch", "rv2_all.sbatch": "04_rule_checks.sbatch",
                "designs2.sbatch": "05_design_simulations.sbatch", "esc_r5.sbatch": "06_eurovision.sbatch",
                "misspec.sbatch": "07_error_distribution_checks.sbatch"}
# lines left out of a released job: designs2's Eurovision designs are rerun, with the final groupings, by esc_r5
SKIP_LINES = {"designs2.sbatch": ("src/esc_analysis.py",)}


def fold(s):
    s = unicodedata.normalize("NFKD", str(s)).encode("ascii", "ignore").decode().lower()
    return " ".join(sorted(s.replace("-", " ").split()))     # order-free: "Last First" = "First Last"


def key(ns, v):
    # coach_id is already the identifier the analyses use: keep its classes exactly
    return str(v) if ns == "C" else fold(v)


def pseudonymise(tables):
    names = {}
    for f, cols in NAME_COLUMNS.items():
        for c, ns in cols.items():
            names.setdefault(ns, set()).update(key(ns, v) for v in tables[f][c] if str(v).strip())
    ids = {ns: {n: f"{ns}{i + 1:05d}" for i, n in enumerate(sorted(v))} for ns, v in names.items()}
    for f, cols in NAME_COLUMNS.items():
        d = tables[f]
        for c, ns in cols.items():
            new = "coach_id" if c == "coach_id" else ("juror_id" if ns == "B" else "voter_id")
            d[c] = [ids[ns][key(ns, v)] if str(v).strip() else "" for v in d[c]]
            d.rename(columns={c: new}, inplace=True)
    return tables


def main():
    out = Path(sys.argv[1]).resolve()
    out.mkdir(parents=True, exist_ok=True)
    for sub in ("src", "tests", "jobs", "data", "results"):     # start clean so renamed files do not linger
        shutil.rmtree(out / sub, ignore_errors=True)
    for sub in ("src", "tests"):
        shutil.copytree(ROOT / sub, out / sub, dirs_exist_ok=True,
                        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    (out / "jobs").mkdir(exist_ok=True)
    for src, dest in RELEASE_JOBS.items():
        text = (ROOT / "jobs" / src).read_text()
        for path in (str(ROOT), str(ROOT.parents[2])):        # the review copy, then the original nhb/
            text = text.replace(path, "${REPO:?set REPO to the repository root}")
        text = "\n".join(l for l in text.splitlines() if not l.startswith("#SBATCH --account")
                         and not l.startswith("#SBATCH --output")
                         and not any(k in l for k in SKIP_LINES.get(src, ()))) + "\n"
        (out / "jobs" / dest).write_text(text)
    (out / "data" / "processed").mkdir(parents=True, exist_ok=True)
    (out / "data" / "raw" / "fifa").mkdir(parents=True, exist_ok=True)
    shutil.copy2(ROOT / "data" / "README.md", out / "data" / "README.md")
    shutil.copy2(ROOT / "data" / "raw" / "fifa" / "manifest.csv", out / "data" / "raw" / "fifa" / "manifest.csv")
    tables = {f.name: pd.read_csv(f, keep_default_na=False, dtype=str) for f in sorted(PROC.glob("*.csv"))
              if f.name not in LEAVE_OUT and f.stat().st_size > 0}
    tables = pseudonymise(tables)
    for f, d in tables.items():
        d = d.drop(columns=[c for c in DROP_COLUMNS.get(f, []) if c in d.columns])
        d.to_csv(out / "data" / "processed" / f, index=False)
    for f in sorted((ROOT / "results").rglob("*")):
        if f.is_file() and f.suffix in (".csv", ".json"):
            dest = out / f.relative_to(ROOT)
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, dest)
    # README, licences and .gitignore of the deposit are kept in release/
    for src, dest in (("README.md", "README.md"), ("LICENSE", "LICENSE"), ("data_LICENSE", "data/LICENSE"),
                      ("gitignore", ".gitignore"), ("CITATION.cff", "CITATION.cff")):
        shutil.copy2(ROOT / "release" / src, out / dest)
    print(f"release written to {out}: {len(tables)} processed tables", file=sys.stderr)


if __name__ == "__main__":
    main()
